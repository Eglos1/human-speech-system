"""
Ollama streaming client.

Streams token-by-token from a local 1B model (llama3.2:1b default).
Each output line is a raw-muscle frame:  "jaw smile pucker brows upper lower squint | words"
"""
from __future__ import annotations

import json
from typing import AsyncIterator

import httpx

OLLAMA_URL = "http://localhost:11434"


class LLMClient:
    def __init__(self, model: str = "llama3.2:1b", base_url: str = OLLAMA_URL, temperature: float = 0.4):
        self.model = model
        self.base_url = base_url
        self.temperature = temperature
        self._client = httpx.AsyncClient(timeout=httpx.Timeout(connect=5.0, read=300.0, write=30.0, pool=10.0))

    async def aclose(self) -> None:
        await self._client.aclose()

    async def stream(self, prompt: str, system: str = "") -> AsyncIterator[str]:
        """Yield text chunks as they are generated by the model."""
        payload = {
            "model": self.model,
            "prompt": prompt,
            "stream": True,
            "options": {
                "temperature": self.temperature,
                "num_predict": 1024,
                "repeat_penalty": 1.15,
                "stop": ["\n\n\n", "\nHuman", "\nYour reply", "\nMy reply", "Human says:"],  # end the frame stream
            },
        }
        if system:
            payload["system"] = system

        async with self._client.stream("POST", f"{self.base_url}/api/generate", json=payload) as resp:
            resp.raise_for_status()
            async for raw_line in resp.aiter_lines():
                if not raw_line.strip():
                    continue
                try:
                    chunk = json.loads(raw_line)
                except json.JSONDecodeError:
                    continue
                piece = chunk.get("response", "")
                if piece:
                    yield piece

    async def generate(self, prompt: str, system: str = "", max_tokens: int = 300) -> str:
        """Non-streaming convenience call."""
        payload = {
            "model": self.model,
            "prompt": prompt,
            "stream": False,
            "options": {
                "temperature": self.temperature,
                "num_predict": max_tokens,
                "repeat_penalty": 1.15,
                "stop": ["\n\n\n", "\nHuman", "\nYour reply", "\nMy reply", "Human says:"],
            },
        }
        if system:
            payload["system"] = system
        resp = await self._client.post(f"{self.base_url}/api/generate", json=payload)
        resp.raise_for_status()
        return resp.json().get("response", "")
